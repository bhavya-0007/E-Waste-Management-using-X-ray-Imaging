def create_synthetic_dataset(n_train=800, n_val=100, n_test=100):
    """
    Generate synthetic dataset for testing pipeline.
    Creates dummy images with random YOLO-format labels.
    
    This is ONLY for testing the pipeline structure.
    Replace with real data for actual training.
    """
    try:
        import numpy as np
        from PIL import Image, ImageDraw, ImageFont
        import json
    except ImportError:
        print("Installing Pillow and numpy...")
        os.system("pip install Pillow numpy --quiet")
        import numpy as np
        from PIL import Image, ImageDraw

    print(f"\n🔧 Creating synthetic dataset...")
    print(f"   Train: {n_train} | Val: {n_val} | Test: {n_test}")
    print("   ⚠️  SYNTHETIC DATA - For pipeline testing only!")
    print("   ⚠️  Use real dataset for actual model training.\n")

    splits = {
        "train": n_train,
        "val": n_val,
        "test": n_test,
    }

    # Color mapping for classes (makes synthetic images distinguishable)
    class_colors = [
        (0, 128, 0),    # circuit_board - green
        (0, 0, 255),    # mobile_phone - blue
        (255, 165, 0),  # battery - orange
        (128, 0, 128),  # cable - purple
        (255, 0, 0),    # charger - red
        (0, 255, 255),  # keyboard - cyan
        (255, 20, 147), # monitor - pink
        (139, 69, 19),  # mouse - brown
        (105, 105, 105),# hard_drive - gray
        (0, 100, 0),    # ram - dark green
        (220, 20, 60),  # cpu - crimson
        (255, 215, 0),  # capacitor - gold
    ]

    total_created = 0
    for split, count in splits.items():
        img_dir = DATA_DIR / "images" / split
        lbl_dir = DATA_DIR / "labels" / split

        for i in range(count):
            # Create synthetic image (640x640)
            w, h = 640, 640
            img = Image.new("RGB", (w, h), color=(200, 200, 200))
            draw = ImageDraw.Draw(img)

            # Draw background noise
            for _ in range(20):
                x1 = random.randint(0, w - 50)
                y1 = random.randint(0, h - 50)
                x2 = x1 + random.randint(10, 80)
                y2 = y1 + random.randint(10, 80)
                draw.rectangle([x1, y1, x2, y2], fill=(random.randint(150, 220),) * 3)

            # Add 1-4 random objects
            n_objects = random.randint(1, 4)
            labels = []
            for _ in range(n_objects):
                cls_id = random.randint(0, len(CLASSES) - 1)
                color = class_colors[cls_id]

                # Random bounding box
                bw = random.randint(50, 200)
                bh = random.randint(50, 200)
                bx = random.randint(0, w - bw)
                by = random.randint(0, h - bh)

                draw.rectangle([bx, by, bx + bw, by + bh], fill=color, outline=(0, 0, 0), width=3)
                draw.text((bx + 5, by + 5), CLASSES[cls_id][:8], fill=(255, 255, 255))

                # YOLO format: class cx cy w h (normalized)
                cx = (bx + bw / 2) / w
                cy = (by + bh / 2) / h
                nw = bw / w
                nh = bh / h
                labels.append(f"{cls_id} {cx:.6f} {cy:.6f} {nw:.6f} {nh:.6f}")

            # Save image
            img_path = img_dir / f"ewaste_{split}_{i:04d}.jpg"
            img.save(img_path, quality=85)

            # Save label
            lbl_path = lbl_dir / f"ewaste_{split}_{i:04d}.txt"
            with open(lbl_path, "w") as f:
                f.write("\n".join(labels))

            total_created += 1

        print(f"   ✅ {split}: {count} images created")

    print(f"\n✅ Synthetic dataset ready: {total_created} total images")
    return True


def try_roboflow_download(api_key=None):
    """
    Download from Roboflow using their Python package.
    Requires free account and API key.
    """
    if not api_key:
        print("ℹ️  No Roboflow API key provided.")
        print("   Get free key at: https://roboflow.com/")
        return False

    try:
        os.system("pip install roboflow --quiet")
        from roboflow import Roboflow

        rf = Roboflow(api_key=api_key)

        # Try multiple public e-waste datasets
        datasets_to_try = [
            ("recycling-fmovz", "e-waste-detection-jxap2", 1),
            ("ewaste", "ewaste-detection", 1),
        ]

        for workspace, project, version in datasets_to_try:
            try:
                print(f"   Trying: {workspace}/{project}...")
                project = rf.workspace(workspace).project(project)
                dataset = project.version(version).download("yolov8")
                print(f"✅ Downloaded: {project}")
                return dataset.location
            except Exception as e:
                print(f"   ⚠️  Failed: {e}")
                continue

        return False
    except Exception as e:
        print(f"⚠️  Roboflow download failed: {e}")
        return False


def reorganize_roboflow_data(source_dir):
    """Reorganize Roboflow download into our structure."""
    source = Path(source_dir)
    splits = ["train", "valid", "test"]
    renames = {"valid": "val"}

    for split in splits:
        target_split = renames.get(split, split)
        for subdir in ["images", "labels"]:
            src = source / split / subdir
            dst = DATA_DIR / subdir / target_split
            if src.exists():
                dst.mkdir(parents=True, exist_ok=True)
                for f in src.iterdir():
                    shutil.copy2(f, dst / f.name)

    print("✅ Data reorganized into 80/10/10 structure.")


def print_dataset_stats():
    """Print statistics about the current dataset."""
    print("\n📊 Dataset Statistics:")
    print("=" * 40)
    total = 0
    for split in ["train", "val", "test"]:
        img_dir = DATA_DIR / "images" / split
        if img_dir.exists():
            count = len(list(img_dir.glob("*.jpg")) + list(img_dir.glob("*.png")))
            print(f"   {split:8s}: {count:5d} images")
            total += count
    print(f"   {'TOTAL':8s}: {total:5d} images")
    print(f"   Classes : {len(CLASSES)}")
    print(f"   Split   : 80/10/10")
    print("=" * 40)


