def main():
    parser = argparse.ArgumentParser(description="Download E-Waste Dataset")
    parser.add_argument("--source", choices=["roboflow", "synthetic", "auto"],
                        default="auto", help="Data source")
    parser.add_argument("--api-key", default=None, help="Roboflow API key")
    parser.add_argument("--synthetic-size", type=int, default=1000,
                        help="Total synthetic images (default 1000 = 800+100+100)")
    args = parser.parse_args()

    print("=" * 60)
    print("  E-WASTE DETECTION DATASET DOWNLOADER")
    print("  80% Train | 10% Validation | 10% Test")
    print("=" * 60)

    create_directory_structure()
    create_dataset_yaml()

    success = False

    if args.source in ("roboflow", "auto") and args.api_key:
        print("\n🌐 Attempting Roboflow download...")
        location = try_roboflow_download(args.api_key)
        if location:
            reorganize_roboflow_data(location)
            success = True

    if not success:
        n = args.synthetic_size
        n_train = int(n * 0.80)
        n_val = int(n * 0.10)
        n_test = n - n_train - n_val

        if args.source == "roboflow":
            print("\n⚠️  Roboflow failed. Falling back to synthetic data.")
            print(f"\n{KAGGLE_DATASETS}")

        create_synthetic_dataset(n_train, n_val, n_test)
        success = True

    print_dataset_stats()

    print("\n✅ Dataset ready!")
    print("\n📌 NEXT STEP: Run training:")
    print("   python train.py")
    print("\n📌 For real data (recommended):")
    print("   1. Download from Kaggle (see links in KAGGLE_DATASETS above)")
    print("   2. Place in data/ folder with YOLO format labels")
    print("   3. Re-run: python train.py")


if __name__ == "__main__":
    main()
